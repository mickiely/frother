import { chromium } from 'playwright'
import fs from 'node:fs'
import assert from 'node:assert/strict'
const fixture = JSON.parse(fs.readFileSync(process.env.FROTHER_TEST_FIXTURE || '/tmp/frother-e2e.json', 'utf8'))
const base = process.env.FROTHER_TEST_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch({headless:true,executablePath:process.env.FROTHER_BROWSER_PATH || chromium.executablePath(),args:['--no-sandbox']})
const errors=[]
const customerContext=await browser.newContext({viewport:{width:390,height:844}})
const staffContext=await browser.newContext({viewport:{width:1280,height:900}})
const secondContext=await browser.newContext({viewport:{width:390,height:844}})
async function pageIn(context,path){const p=await context.newPage();p.on('pageerror',e=>errors.push(e.message));await p.goto(base+path);return p}
async function login(page,email){await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Password',{exact:true}).fill(fixture.password);await page.getByRole('button',{name:'Sign in',exact:true}).click();}
try {
 const customer=await pageIn(customerContext,`/pilot/${fixture.slug}`)
 await login(customer,fixture.customerEmail)
 await customer.getByRole('heading',{name:'Join this venue'}).waitFor()
 await customer.getByLabel('First name',{exact:true}).fill('Browser Test')
 await customer.getByLabel('Mobile (for staff lookup)',{exact:true}).fill('0400000011')
 await customer.getByRole('button',{name:'Join rewards',exact:true}).click()
 await customer.getByRole('heading',{name:'Hey, Browser Test.'}).waitFor()
 await customer.reload()
 await customer.getByRole('heading',{name:'Hey, Browser Test.'}).waitFor()
 console.log('PASS customer joins and survives refresh')
 const staff=await pageIn(staffContext,`/pilot/${fixture.slug}/staff`)
 await login(staff,fixture.staffEmail)
 await staff.getByRole('button',{name:/Browser Test/}).click()
 for(let n=0;n<3;n++) {await staff.getByRole('button',{name:'Add 3',exact:true}).click();await staff.getByRole('button',{name:'Add 3',exact:true}).waitFor({state:'visible'});await staff.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Add 3')?.disabled);}
 await staff.getByText('Reward ready — show staff.',{exact:true}).waitFor()
 console.log('PASS staff awards 9 saved stamps')
 const second=await pageIn(secondContext,`/pilot/${fixture.slug}`)
 await login(second,fixture.customerEmail)
 await second.getByText('Reward ready — show staff.',{exact:true}).waitFor()
 assert.equal(await second.getByRole('button',{name:'Redeem one reward',exact:true}).count(),0)
 console.log('PASS same customer reads balance on separate device; no customer award/redeem controls')
 await staff.getByRole('button',{name:'Redeem one reward',exact:true}).click()
 await staff.getByText('Reward redeemed. Remaining stamps are saved.',{exact:true}).waitFor()
 assert.equal(await staff.getByRole('button',{name:'Redeem one reward',exact:true}).isDisabled(),true)
 await second.getByRole('button',{name:'Refresh saved balance',exact:true}).click()
 await second.getByText('9 more until your reward.',{exact:true}).waitFor()
 console.log('PASS single redemption and updated customer balance')
 await second.getByLabel('Email offers',{exact:true}).check()
 await second.getByRole('button',{name:'Save preferences',exact:true}).click()
 await second.getByText('Communication preferences saved.',{exact:true}).waitFor()
 await second.reload();await second.getByRole('heading',{name:'Hey, Browser Test.'}).waitFor()
 assert.equal(await second.getByLabel('Email offers',{exact:true}).isChecked(),true)
 await second.getByLabel('Email offers',{exact:true}).uncheck()
 await second.getByRole('button',{name:'Save preferences',exact:true}).click()
 await second.getByText('Communication preferences saved.',{exact:true}).waitFor()
 console.log('PASS optional consent persists and can be withdrawn')
 await customer.goto(base+`/pilot/${fixture.slug}/staff`)
 await customer.getByRole('heading',{name:'Staff access required',exact:true}).waitFor()
 console.log('PASS customer denied staff screen')
 const demo=await pageIn(customerContext,'/venue/demo-cafe')
 await demo.getByRole('link',{name:'Join rewards',exact:true}).waitFor()
 console.log('PASS existing demo remains accessible')
 await staff.screenshot({path:'/tmp/frother-pilot-staff.png',fullPage:true})
 await second.screenshot({path:'/tmp/frother-pilot-customer.png',fullPage:true})
 assert.deepEqual(errors,[])
 console.log('PASS no browser runtime errors')
} finally { await browser.close() }
